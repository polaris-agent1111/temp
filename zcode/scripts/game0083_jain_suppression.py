S_MED = ES * np.log(2)
def sojourn(g, t0, S=S_MED):
    dn = LAM - (CMB - g / 8) / ES
    R = CMB - g / 8
    N0 = 1 + dn * t0
    t_end = N0 * (np.exp(S * dn / R) - 1) / dn
    return (R * 8) / N0, t_end, S / CMB
