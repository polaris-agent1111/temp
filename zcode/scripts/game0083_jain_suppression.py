P("|---|---|---|---|---|---|---|---|---|")
def jain_multi(g, N):
    """1 条我方流（g）+ N 条背景流均分 (C-g) 的 Jain 指数."""
    if N <= 0:
        return 1.0
    xbg = (C - g) / N
    tot = g + C - g
    s2 = g * g + N * xbg * xbg
    return tot * tot / ((1 + N) * s2)
